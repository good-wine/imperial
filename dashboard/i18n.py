def current_lang(session_lang: str | None = None) -> str:
    """Resolve active language: explicit choice > env default > English."""
    if session_lang in _STRINGS:
        return session_lang
    if DEFAULT_LANG in _STRINGS:
        return DEFAULT_LANG
    return "en"


def t(lang: str, key: str, **kwargs: object) -> str:
    """Translate `key`, falling back to English, then formatting."""
    table = _STRINGS.get(lang, {})
    template = table.get(key, _STRINGS["en"].get(key, key))
    try:
        return template.format(**kwargs)
    except (KeyError, IndexError, ValueError):
        return template
